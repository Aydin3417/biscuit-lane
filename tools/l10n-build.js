/* The other languages, from the files a translator works in to the one
   module the game reads.

     node tools/l10n-build.js           write src/js/06-l10n.js
     node tools/l10n-build.js --check   say whether it is up to date

   src/l10n/<lang>.json is the source: { strings, one, inline }, the
   shape tools/l10n-source.js asks for and tools/l10n-check.js holds a
   file to. src/l10n/units.json is eight words nobody's regex finds —
   the ability units, which the data keeps as ['tile', 'tiles'] pairs.

   What comes out adds a row to STRINGS and ONE (05-i18n.js) and to
   XLATE (00-util.js) for each language. English and Turkish are not
   here: they are written in the source beside the things they name,
   and stay there. A file that fails the check is left out rather than
   shipped half-right, and the build says so. */
const fs = require('fs');
const path = require('path');
const { check } = require('./l10n-check.js');

const dir = path.join(__dirname, '..', 'src', 'l10n');
const OUT = path.join(__dirname, '..', 'src', 'js', '06-l10n.js');
const ORDER = ['es', 'de', 'fr', 'pt', 'it'];

function build() {
  const units = fs.existsSync(path.join(dir, 'units.json')) ? JSON.parse(fs.readFileSync(path.join(dir, 'units.json'), 'utf8')) : {};
  const parts = [
    '/* GENERATED by tools/l10n-build.js from src/l10n/*.json — do not edit by hand.',
    '   Spanish, German, French, Portuguese and Italian: the string table,',
    '   its singular forms, and every sentence the data carries inline,',
    '   keyed by its English (see loc() in 00-util.js). */'
  ];
  const left = [];
  ORDER.forEach(l => {
    const f = path.join(dir, l + '.json');
    if (!fs.existsSync(f)) { left.push(l + ' (no file)'); return; }
    const bad = check(f);
    if (bad.length) { left.push(l + ' (' + bad.length + ' problems: ' + bad[0] + ')'); return; }
    const d = JSON.parse(fs.readFileSync(f, 'utf8'));
    const inline = Object.assign({}, d.inline, units[l] || {});
    parts.push('STRINGS.' + l + ' = ' + JSON.stringify(d.strings) + ';');
    parts.push('ONE.' + l + ' = ' + JSON.stringify(d.one) + ';');
    parts.push('XLATE.' + l + ' = ' + JSON.stringify(inline) + ';');
  });
  return { text: parts.join('\n') + '\n', left };
}

if (require.main === module) {
  const { text, left } = build();
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    console.log(now === text ? '06-l10n.js is up to date' : '06-l10n.js is STALE: run node tools/l10n-build.js');
    left.forEach(x => console.log('  left out: ' + x));
    process.exit(now === text && !left.length ? 0 : 1);
  }
  fs.writeFileSync(OUT, text);
  console.log('wrote 06-l10n.js, ' + Math.round(text.length / 1024) + ' KB' + (left.length ? '; LEFT OUT: ' + left.join(', ') : ''));
}
module.exports = { build };
